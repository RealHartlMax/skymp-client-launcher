// Runs the fork's real public asset routes and heartbeat metadata against isolated PHP roots.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { startPhpFixture } from './php-master-smoke.mjs';
const require = createRequire('D:/GitHub/skymp/skymp5-server/package.json');
const { buildSync } = require('esbuild');
const Koa = require('koa'), Router = require('koa-router');
const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'skymp-server-assets-'));
const checks = [];
let fixture, server;
try {
  buildSync({ entryPoints: ['D:/GitHub/skymp/skymp5-server/ts/serverAssets.ts'], outfile: path.join(temporary, 'assets.cjs'), bundle: true, platform: 'node', format: 'cjs' });
  const { registerServerAssets, describeServerAssets } = require(path.join(temporary, 'assets.cjs'));
  const logo = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+/a9sAAAAASUVORK5CYII=', 'base64');
  const app = new Koa(), router = new Router();
  registerServerAssets(router, temporary);
  app.use(router.routes());
  server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const origin = `http://127.0.0.1:${server.address().port}`;
  assert.deepEqual(await describeServerAssets(temporary), {});
  assert.equal((await fetch(origin + '/api/launcher/assets/logo.png')).status, 404);
  await fs.writeFile(path.join(temporary, 'logo.png'), logo);
  await fs.writeFile(path.join(temporary, 'banner.png'), logo);
  let assets = await describeServerAssets(temporary);
  assert.equal(assets.logo.sha256, createHash('sha256').update(logo).digest('hex'));
  const downloaded = await fetch(origin + assets.logo.path);
  assert.equal(downloaded.headers.get('content-type'), 'image/png');
  assert.deepEqual(Buffer.from(await downloaded.arrayBuffer()), logo);
  assert.equal((await fetch(origin + assets.logo.path, { headers: { 'if-none-match': `"${assets.logo.sha256}"` } })).status, 304);
  assert.equal((await fetch(origin + assets.logo.path + '?v=' + '0'.repeat(64))).status, 409);
  assert.equal((await fetch(origin + '/api/launcher/assets/server-settings.json')).status, 404);
  checks.push('Only optional logo.png and banner.png from the server root are public; exact bytes, revisions and ETags work.');
  await fs.writeFile(path.join(temporary, 'logo.png'), '<svg><script>alert(1)</script></svg>');
  assert.equal((await fetch(origin + assets.logo.path)).status, 404);
  assert(!('logo' in await describeServerAssets(temporary)));
  await fs.writeFile(path.join(temporary, 'logo.png'), logo);
  const changed = Buffer.concat([logo, Buffer.from('new revision')]);
  await fs.writeFile(path.join(temporary, 'banner.png'), changed);
  assets = await describeServerAssets(temporary);
  assert.notEqual(assets.banner.sha256, assets.logo.sha256);
  checks.push('Invalid optional files do not disable discovery; changed images receive a new content hash.');
  fixture = await startPhpFixture({ resourceUrl: origin });
  const heartbeat = data => fetch(fixture.api + '/api/servers/' + fixture.masterKey, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Actual server name', online: 0, maxPlayers: 32, assets: data }) });
  assert.equal((await heartbeat(assets)).status, 200);
  const list = await (await fetch(fixture.api + '/list.php')).json();
  const published = list.find(row => row.id === fixture.serverUid);
  assert(published.iconUrl.startsWith(fixture.manage + '/server-image.php?'));
  assert(published.bannerUrl.includes(assets.banner.sha256));
  const proxied = await fetch(published.iconUrl);
  assert.equal(proxied.status, 200);
  assert.equal(proxied.headers.get('content-type'), 'image/png');
  assert.deepEqual(Buffer.from(await proxied.arrayBuffer()), logo);
  assert.equal((await fetch(published.iconUrl, { headers: { 'if-none-match': `"${assets.logo.sha256}"` } })).status, 304);
  checks.push('Authenticated heartbeats publish HTTPS-capable web image URLs; the gateway retrieves and verifies original server PNG bytes.');
  assert.equal((await heartbeat({ logo: { ...assets.logo, path: '/server-settings.json' } })).status, 400);
  assert.equal((await heartbeat({ logo: { ...assets.logo, size: 9 * 1024 * 1024 } })).status, 400);
  assert.equal((await heartbeat({ logo: { ...assets.logo, sha256: 'invalid' } })).status, 400);
  await fs.writeFile(path.join(temporary, 'logo.png'), changed);
  assert.equal((await fetch(published.iconUrl)).status, 502);
  await fs.unlink(path.join(temporary, 'banner.png'));
  assets = await describeServerAssets(temporary);
  assert.equal((await heartbeat(assets)).status, 200);
  const refreshed = (await (await fetch(fixture.api + '/list.php')).json()).find(row => row.id === fixture.serverUid);
  assert.equal(refreshed.bannerUrl, '');
  assert.notEqual(refreshed.iconUrl, published.iconUrl);
  assert.equal((await fetch(published.iconUrl)).status, 404);
  checks.push('Path substitution, invalid hashes and oversized descriptors are rejected; file deletion and stale revisions update safely.');
  const publisher = buildSync({ entryPoints: ['D:/GitHub/skymp/skymp5-server/ts/systems/masterClient.ts'], bundle: true, platform: 'node', format: 'cjs', external: ['axios'], write: false }).outputFiles[0].text;
  const NativeModule = require('node:module');
  const publisherModule = new NativeModule('master-client-test');
  publisherModule.require = name => name === 'axios' ? require('axios') : require(name);
  publisherModule._compile(publisher, path.join(temporary, 'master.cjs'));
  const originalCwd = process.cwd();
  const originalSignals = new Map(['SIGINT', 'SIGTERM'].map(signal => [signal, new Set(process.listeners(signal))]));
  try {
    process.chdir(temporary);
    const client = new publisherModule.exports.MasterClient(() => {}, 7777, '127.0.0.1', fixture.api, 32, 'Fixture server', fixture.masterKey, 15000, false, 'Roleplay', 'DE', fixture.serverUid);
    await client.initAsync();
    const discovered = (await (await fetch(fixture.api + '/list.php')).json()).find(row => row.id === fixture.serverUid);
    assert.equal(discovered.iconUrl, refreshed.iconUrl); assert.equal(discovered.name, 'Fixture server'); assert.equal(discovered.max_players, 32);
    await fs.writeFile(path.join(temporary, 'banner.png'), logo);
    await client.sendHeartbeat(0, 'periodic');
    const again = (await (await fetch(fixture.api + '/list.php')).json()).find(row => row.id === fixture.serverUid);
    assert(again.bannerUrl.includes(createHash('sha256').update(logo).digest('hex')));
    assert.equal(again.server_status, 'online');
    await client.sendHeartbeat(0, 'shutdown');
    const stopped = (await (await fetch(fixture.api + '/list.php')).json()).find(row => row.id === fixture.serverUid);
    assert.equal(stopped.server_status, 'offline'); assert.equal(stopped.current_players, 0); assert.equal(stopped.name, 'Fixture server');
    await client.sendHeartbeat(0, 'initial');
    const restarted = (await (await fetch(fixture.api + '/list.php')).json()).find(row => row.id === fixture.serverUid);
    assert.equal(restarted.server_status, 'online');
  } finally {
    process.chdir(originalCwd);
    for (const [signal, previous] of originalSignals) for (const listener of process.listeners(signal)) if (!previous.has(listener)) process.removeListener(signal, listener);
  }
  checks.push('The actual MasterClient discovers server-root images, reports shutdown as offline immediately and returns online on restart.');
  const restricted = await startPhpFixture({ resourceUrl: origin, allowPrivateResources: false });
  try {
    await fetch(restricted.api + '/api/servers/' + restricted.masterKey, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ name: 'Actual server name', maxPlayers: 32, online: 0, assets }) });
    const entry = (await (await fetch(restricted.api + '/list.php')).json()).find(row => row.id === restricted.serverUid);
    assert.equal((await fetch(entry.iconUrl)).status, 502);
  } finally { await restricted.stop(); }
  checks.push('Production image fetching retains SSRF restrictions and never follows arbitrary image URLs.');
  console.log(JSON.stringify({ ok: true, checks, cases: checks.length, gameStarted: false, publicServerContacted: false }));
} finally {
  await fixture?.stop();
  if (server) await new Promise(resolve => server.close(resolve));
  assert.equal(path.dirname(path.resolve(temporary)), path.resolve(os.tmpdir()));
  assert(path.basename(temporary).startsWith('skymp-server-assets-'));
  await fs.rm(temporary, { recursive: true, force: true });
}
