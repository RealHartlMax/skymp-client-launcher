<?php
function available_languages(): array
{
    return [
        'de' => 'Deutsch',
        'en' => 'English',
        'ru' => 'Русский',
    ];
}

function current_language(): string
{
    static $resolvedLanguage = null;

    if ($resolvedLanguage !== null) {
        return $resolvedLanguage;
    }

    $supported = available_languages();
    $queryLanguage = trim((string) ($_GET['lang'] ?? ''));

    if (isset($supported[$queryLanguage])) {
        $resolvedLanguage = $queryLanguage;
        setcookie('skymp_lang', $resolvedLanguage, [
            'expires' => time() + 31536000,
            'path' => '/',
            'samesite' => 'Lax',
        ]);

        return $resolvedLanguage;
    }

    $cookieLanguage = trim((string) ($_COOKIE['skymp_lang'] ?? ''));

    if (isset($supported[$cookieLanguage])) {
        $resolvedLanguage = $cookieLanguage;
        return $resolvedLanguage;
    }

    $acceptLanguage = strtolower((string) ($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? ''));

    foreach (array_keys($supported) as $languageCode) {
        if (str_contains($acceptLanguage, $languageCode)) {
            $resolvedLanguage = $languageCode;
            return $resolvedLanguage;
        }
    }

    $resolvedLanguage = 'en';
    return $resolvedLanguage;
}

